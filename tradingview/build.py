"""Build the TradingView scripts from tradingview/src/.

The indicator and the strategy share one copy of the logic (src/core.pine).
Each wrapper (src/indicator.pine, src/strategy.pine) has a //@@CORE@@ marker
where the core is pasted. Pine has no #include, so this is how they stay in sync.

    python tradingview/build.py          # write the .pine files
    python tradingview/build.py --check  # fail if they are out of date
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "src"
MARKER = "//@@CORE@@"
TARGETS = {
    "indicator.pine": "ICT_OTE_Indicator.pine",
    "strategy.pine": "ICT_OTE_Strategy.pine",
}
BANNER = (
    "// Generated by tradingview/build.py from tradingview/src/. Edit the source, not this file.\n"
    "// Copy this whole file into TradingView's Pine Editor.\n"
)


def render(wrapper: str) -> str:
    text = (SRC / wrapper).read_text()
    if text.count(MARKER) != 1:
        raise SystemExit(f"{wrapper}: expected exactly one {MARKER}")
    core = (SRC / "core.pine").read_text().rstrip() + "\n"
    version, rest = text.split("\n", 1)  # //@version must stay on line 1
    return version + "\n" + BANNER + rest.replace(MARKER, core)


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for wrapper, out in TARGETS.items():
        content = render(wrapper)
        path = HERE / out
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(out)
        else:
            path.write_text(content)
            print(f"wrote {path.relative_to(HERE.parent)}")
    if stale:
        print("out of date: " + ", ".join(stale) + " (run python tradingview/build.py)")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
